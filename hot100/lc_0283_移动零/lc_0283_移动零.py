#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# ============================================================
# LeetCode 283. 移动零 (Move Zeroes)  |  难度：简单
# ------------------------------------------------------------
# 一句话：把数组里所有 0 移到末尾，非零元素保持原相对顺序，原地操作（不能复制数组）。
#         例 [0,1,0,3,12] -> [1,3,12,0,0]。
# 涉及知识点：双指针（快慢指针）· 原地修改 · 元组交换赋值 · 单次遍历
#
# 提交方式：把 ① 段 class Solution 整段复制回 LeetCode 提交区即可
#          （moveZeroes 直接改 nums、返回 None；方法签名与题面完全一致）；
#          本文件整体同时也是 ACM/OJ 程序——顶层直接跑 main()，从 stdin 读、往 stdout 写。
#
# 本地判题（in.txt 里串了 8 组用例）：
#     python lc_0283_移动零.py < in.txt
#     diff <(python lc_0283_移动零.py < in.txt) out.txt && echo PASS
#
# 脚本结构（四段解耦，改题时只动对应那一段）：
#   ① class Solution  -- 纯算法，与 LeetCode 提交区一致，不碰任何 IO
#   ② parse_input()   -- stdin 文本 -> 逐组实参（唯一负责"读"的地方）
#   ③ format_output() -- 算法返回值 -> 输出字符串（唯一负责"写"的地方）
#   ④ main()          -- ACM 主流程：逐组算、逐组输出
#
# 注释约定（算法层强制）：每个 API / 关键字 / 语法糖首次出现处都要解释，
# 三要素齐全 -- 作用 · 关键参数（含默认值）· 返回或副作用；同一 API 之后只写短注释。
# ============================================================

import sys
from typing import List


# ============================================================
# ① 核心算法：可整段复制回 LeetCode 提交区（方法签名与题面完全一致）
#    - 只依赖标准库
#    - 禁止出现 input() / print() / sys.stdin，保证 Solution 能脱离 IO 单独使用
# ============================================================
class Solution:
    def moveZeroes(self, nums: List[int]) -> None:
        """快慢双指针原地搬移：慢指针指向"下一个非零数该落的位置"，快指针扫描全数组。

        思路：快指针 fast 从头扫到尾，遇到非零数就把它和慢指针 slow 指向的位置交换，
              然后 slow 前进一格。这样每处理完一个非零数，它前面就全部是非零数；
              扫描结束时 slow 恰好停在"非零区"末尾，剩下的位置自然全是 0，即堆在数组末尾。
        为什么不能复制数组：题目明确要求原地、O(1) 额外空间，开新数组装结果就违反约束。
        为什么快：暴力做法是每遇到一个 0 就整体挪动后面所有元素（O(n^2)）；
                 双指针只做一次扫描、至多 n 次交换，把复杂度压到 O(n)。
        时间复杂度 O(n)：快指针恰好扫过 n 个元素。
        空间复杂度 O(1)：只用了两个整数下标，没有开任何与 n 有关的容器。

        关键 Python 语法（首次出现处详解，后续同款写法不再展开）：
          - range(n)：生成 [0, n) 的整数序列，配合 len(nums) 拿到每个下标。
          - `a, b = b, a` 元组交换赋值：右侧先整体求值成元组，再按位置写回左侧，
            一步完成交换，不需要第三个临时变量。
          - 方法签名 -> None：表示"不返回有意义的值"，原地改完 nums 就结束
            （LeetCode 判题时直接检查调用后的 nums）。
        """
        slow = 0                                    # 慢指针：下一个非零元素应放置的位置
        for fast in range(len(nums)):               # 【API】range(停止值)：生成 0 到 n-1 的整数序列
                                                    #   len(nums) 得到元素个数，两者拼出全部下标
            if nums[fast] != 0:                     # 只搬非零元素；0 由后面的交换自然带走
                nums[slow], nums[fast] = nums[fast], nums[slow]   # 【语法】元组交换赋值：右侧先整体求值成
                                                    #   (nums[fast], nums[slow])，再按位置写回左侧，
                                                    #   一步互换两值，无需第三个临时变量
                                                    #   【易错】当 slow == fast（前面没出现过 0）时
                                                    #   是自我交换，结果不变，逻辑依然正确
                slow += 1                           # 非零区右扩一格，慢指针指向下一个空位


# ============================================================
# ② 输入解析层：stdin 原始文本 -> 逐组算法入参
#    唯一允许"读输入"的地方；交给算法的是干净的 Python 对象。
#    格式（见 题目.md）：每组两行 -- n / n 个整数，多组依次排列，读到 EOF 为止。
# ============================================================
def parse_input(text: str):
    """把 stdin 全文按组切开，逐组 yield 该组的数组 nums。

    【语法】yield 让函数变成生成器：main 里 for 一次拿一组，组数不定也能读到 EOF 自然结束。
    【语法】str.split() 不带参数 = 按任意空白切分并丢掉空串，所以一行或多行写法都能解析。
    """
    tokens = text.split()
    pos = 0                                     # 游标推进，别用 pop(0)（O(n)，多组会退化）
    while pos < len(tokens):
        n = int(tokens[pos]); pos += 1           # 【API】int(字符串)：输入全是字符串，必须自己转类型
        nums = [int(t) for t in tokens[pos:pos + n]]   # 【语法】列表推导式：把 n 个 token 逐个转 int
                                                        # 【语法】切片 tokens[a:b] 取左闭右开区间 [a,b)
        pos += n
        yield nums


# ============================================================
# ③ 输出格式化层：算法返回值 -> 该组用例的输出文本
#    只在这里做格式适配。本题结果就是修改后的 nums，输出为空格分隔的一行。
# ============================================================
def format_output(nums) -> str:
    """把"移动零之后的数组"输出成一行空格分隔的整数。

    【API】" ".join(可迭代对象)：用空格把序列拼成一个字符串，
      参数必须是字符串序列，所以先用 map(str, ...) 把每个整数转成字符串。
    【API】map(函数, 可迭代对象)：惰性逐个调用函数，join 时才真正取值。
    """
    return " ".join(map(str, nums))


# ============================================================
# ④ 驱动层：ACM 主流程（顶层直接调用，提交时不加 __main__ 包裹）
# ============================================================
def main():
    outs = []
    for nums in parse_input(sys.stdin.read()):  # 【API】sys.stdin.read()：一次读完整个标准输入
                                                #   返回 str；判题机把输入重定向进来，能读到全部内容
        Solution().moveZeroes(nums)             # 原地修改 nums；方法返回 None，结果就在 nums 里
        outs.append(format_output(nums))
    if outs:                                    # 空输入就别输出，否则会凭空多一个空行
        sys.stdout.write("\n".join(outs) + "\n")    # 【API】sys.stdout.write(s)：写字符串、不自动换行
                                                    #   所以手动补 "\n"；比多组循环 print 更快


main()
