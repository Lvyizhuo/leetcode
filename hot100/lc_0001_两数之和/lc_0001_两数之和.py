#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# ============================================================
# LeetCode 1. 两数之和 (Two Sum)  |  难度：简单
# ------------------------------------------------------------
# 一句话：在数组里找出和为 target 的两个下标（每组输入只有一组答案，同一下标不能用两次）。
# 涉及知识点：哈希表（dict）· 一次遍历 · 边查边存 · enumerate · 空间换时间
#
# 提交方式：**整个文件就是 ACM/OJ 提交代码**——顶层直接跑 main()，从 stdin 读、往 stdout 写。
#
# 本地判题（in.txt 里串了 5 组用例）：
#     python lc_0001_两数之和.py < in.txt
#     diff <(python lc_0001_两数之和.py < in.txt) out.txt && echo PASS
#
# 脚本结构（四段解耦，改题时只动对应那一段）：
#   ① class Solution  -- 纯算法，与 LeetCode 提交区一致，不碰任何 IO
#   ② parse_input()   -- stdin 文本 -> 逐组实参（唯一负责"读"的地方）
#   ③ format_output() -- 算法返回值 -> 输出字符串（唯一负责"写"的地方）
#   ④ main()          -- ACM 主流程：逐组算、逐组输出
#
# 注释约定（算法层强制）：每个 API / 关键字 / 语法糖首次出现处都要解释，
# 三要素齐全 -- 作用 · 关键参数（含默认值）· 返回或副作用；同一 API 之后只写短注释。
# ============================================================

import sys
from typing import List


# ============================================================
# ① 核心算法：可整段复制回 LeetCode 提交区（方法签名与题面完全一致）
#    - 只依赖标准库
#    - 禁止出现 input() / print() / sys.stdin，保证 Solution 能脱离 IO 单独使用
# ============================================================
class Solution:
    def twoSum(self, nums: List[int], target: int) -> List[int]:
        """一次遍历 + 哈希表：边扫边记，扫到 x 时查 target - x 有没有出现过。

        为什么快：把"找补数"从遍历数组（O(n)）换成查哈希表（O(1)），
                  总复杂度从暴力双重循环的 O(n^2) 降到 O(n)。
        时间复杂度 O(n)：每个元素最多进表一次、查表一次。
        空间复杂度 O(n)：最坏情况（答案在末尾）哈希表存下前 n-1 个元素。

        关键 Python 语法（首次出现处详解，后续同款写法不再展开）：
          - dict（哈希表）：键 -> 值的映射，底层哈希表，`key in d` 与 `d[key]` 平均都是 O(1)。
          - enumerate(iterable, start=0)：遍历时同时给出下标和元素，
            返回 (下标, 元素) 二元组，省掉手写 range(len(nums)) 再索引的麻烦。
          - 循环变量解包：`for i, x in enumerate(nums)` 直接把二元组拆成两个名字。
        """
        seen = {}                       # 【dict】哈希表：已扫过的元素 -> 它的下标
                                        # 只登记"扫过的"，所以不会用同一个下标两次

        for i, x in enumerate(nums):    # 【API】enumerate(可迭代对象, start=0)
                                        #   作用：遍历时额外给出下标，免去 range(len()) 写法
                                        #   关键参数：start 默认 0，可改成 1 起计数（本题必须从 0 起）
                                        #   返回：一个惰性迭代器，每次产出 (下标, 元素)
            need = target - x           # 还差多少才能和 x 凑成 target，即"要找的补数"

            if need in seen:            # 【语法】`in` 作用于 dict 时判断的是"键是否存在"
                                        #   平均 O(1)；对比：`in` 作用于 list 是逐个比对，O(n)
                return [seen[need], i]  # 补数在前面出现过 -> 命中；顺序按"先出现的下标在前"
                                        # 【易错】写成 [i, seen[need]] 顺序反了，判题会判错

            seen[x] = i                 # 没命中才把自己登记进去：先查后存
                                        # 【易错】若先存后查，同一元素会匹配到自己（nums=[3,3], target=6
                                        #   会得到 [0,0]，等于重复使用了同一个元素）

        return []                       # 题目保证一定有解，这行只是语法兜底，正常跑不到


# ============================================================
# ② 输入解析层：stdin 原始文本 -> 逐组算法入参
#    唯一允许"读输入"的地方；交给算法的是干净的 Python 对象。
#    格式（见 题目.md）：每组三行 —— n / n 个整数 / target，多组依次排列，读到 EOF 为止。
# ============================================================
def parse_input(text: str):
    """把 stdin 全文按组切开，逐组 yield (nums, target)。

    【语法】yield 让函数变成生成器：main 里 for 一次拿一组，
            不用把全部用例先存进内存，也就天然支持"组数不定、读到 EOF 为止"。
    【语法】str.split() 不带参数 = 按任意空白切分并丢掉空串，
            所以每组是写成三行还是挤成一行都能正确切分。
    """
    tokens = text.split()
    pos = 0                                     # 游标：tokens 是列表，用下标推进最直观
                                                # 【易错】别用 tokens.pop(0) 删头：list.pop(0) 是 O(n)，
                                                #   多组数据会退化成 O(n^2)
    while pos < len(tokens):
        n = int(tokens[pos]); pos += 1           # 【API】int(字符串)：输入全是字符串，必须自己转类型
        nums = [int(t) for t in tokens[pos:pos + n]]    # 【语法】切片左闭右开，正好取 n 个
        pos += n
        target = int(tokens[pos]); pos += 1
        yield nums, target


# ============================================================
# ③ 输出格式化层：算法返回值 -> 该组用例的输出文本
#    只在这里做格式适配（空格分隔？带方括号？定位小数？），算法不用改。
# ============================================================
def format_output(result) -> str:
    """两个下标用空格分隔成一行，如 "0 1"（多个下标 [0,2] -> "0 2"）。

    【API】str.join(可迭代对象)：用分隔符把多个字符串拼成一个；
      这里先把每个数字用 map(str, ...) 转成字符串再拼；
      对比循环里 s += x：那是每轮新建字符串，整体 O(n^2)，join 是一次性算好长度再填，O(n)。
    """
    return " ".join(map(str, result))


# ============================================================
# ④ 驱动层：ACM 主流程（顶层直接调用，提交时不加 __main__ 包裹）
# ============================================================
def main():
    outs = []
    for nums, target in parse_input(sys.stdin.read()):   # 【API】sys.stdin.read()：一次读完整个标准输入
                                                         #   返回 str；判题机把输入重定向进来，能读到全部内容
        outs.append(format_output(Solution().twoSum(nums, target)))
    if outs:                                    # 空输入就别输出，否则会凭空多一个空行
        sys.stdout.write("\n".join(outs) + "\n")    # 【API】sys.stdout.write(s)：写字符串、不自动换行，
                                                    #   所以手动补 "\n"；比多组循环 print 更快


main()
