#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# ============================================================
# LeetCode 128. 最长连续序列 (Longest Consecutive Sequence)  |  难度：中等
# ------------------------------------------------------------
# 一句话：给未排序整数数组 nums，找出"数字连续"的最长序列长度（不要求在原数组里相邻）。
#         例 [100,4,200,1,3,2] 中最长是 [1,2,3,4]，长度 4。要求时间 O(n)。
# 涉及知识点：哈希集合（set）· 只从"序列起点"开始数 · 摊还分析 · 去重
#
# 提交方式：把 ① 段 class Solution 整段复制回 LeetCode 提交区即可（方法签名与题面一致）；
#          本文件整体同时也是 ACM/OJ 程序——顶层直接跑 main()，从 stdin 读、往 stdout 写。
#
# 本地判题（in.txt 里串了 11 组用例）：
#     python lc_0128_最长连续序列.py < in.txt
#     diff <(python lc_0128_最长连续序列.py < in.txt) out.txt && echo PASS
#
# 脚本结构（四段解耦，改题时只动对应那一段）：
#   ① class Solution  -- 纯算法，与 LeetCode 提交区一致，不碰任何 IO
#   ② parse_input()   -- stdin 文本 -> 逐组实参（唯一负责"读"的地方）
#   ③ format_output() -- 算法返回值 -> 输出字符串（唯一负责"写"的地方）
#   ④ main()          -- ACM 主流程：逐组算、逐组输出
#
# 注释约定（算法层强制）：每个 API / 关键字 / 语法糖首次出现处都要解释，
# 三要素齐全 -- 作用 · 关键参数（含默认值）· 返回或副作用；同一 API 之后只写短注释。
# ============================================================

import sys
from typing import List


# ============================================================
# ① 核心算法：可整段复制回 LeetCode 提交区（方法签名与题面完全一致）
#    - 只依赖标准库
#    - 禁止出现 input() / print() / sys.stdin，保证 Solution 能脱离 IO 单独使用
# ============================================================
class Solution:
    def longestConsecutive(self, nums: List[int]) -> int:
        """哈希集合 + 只从"序列起点"向外数：把查找从 O(n) 降到 O(1)。

        思路：先把所有数丢进集合（顺便去重）。遍历每个数 x，只有当 x-1 不在集合里时，
              x 才是一段连续序列的"最小端点"（起点）；这时再从 x 开始一路 +1 往后数，
              数到集合里没有 y+1 为止，这段长度就是候选答案。x-1 存在的数是"序列中间点"，
              直接跳过——因为它所在的那段已经被它的起点数过一遍了。
        为什么 O(n)：暴力做法对每个数都往后数，一条长序列会被反复数很多次，最坏 O(n^2)；
                    用"只从起点数"这一刀，每个元素在 while 里最多被碰一次（要么当起点
                    被数一遍，要么当中间点直接跳过），所以总摊还是 O(n)。
        时间复杂度 O(n)：建集合 O(n)；外层遍历每个数 O(1) 判断；while 累加的总步数 ≤ n。
        空间复杂度 O(n)：集合最坏存下全部 n 个不同的数。

        关键 Python 语法（首次出现处详解，后续同款写法不再展开）：
          - set(可迭代对象)：哈希集合，自动去重；`x in s` 平均 O(1)，
            对比 `x in list` 是逐个比对 O(n)——这正是本题能 O(n) 的关键。
          - `x - 1 not in num_set`：集合成员判断，平均 O(1)；
            "not in" 只是 `in` 的否定，语义和复杂度完全一样。
          - while 循环：条件为真就一直走；这里靠 y 不断 +1 最终脱离集合而自然结束。
          - max(a, b)：返回较大者，用来持续刷新"目前见过的最长长度"。
        """
        num_set = set(nums)                 # 【set】哈希集合：自动去重 + O(1) 成员判断
                                            #   【API】set(可迭代对象)：遍历入参建集合，O(n)
                                            #   为什么必须用 set 而不是 list：本题每次都要问
                                            #     "y+1 在不在"，list 里是 O(n)，set 里是 O(1)
        best = 0                            # 记录最长长度；空数组时直接返回 0，天然覆盖边界

        for x in num_set:                   # 遍历集合而非 nums：重复元素只看一次，省得白数
            if x - 1 not in num_set:        # 【关键】x-1 不在集合里 -> x 是一段序列的最小端点（起点）
                                            #   只有起点才需要往后数；中间点一定已被它的起点覆盖
                y = x                       # 从起点开始，一路向右延伸
                while y + 1 in num_set:     # 【语法】while 对象：条件为真就循环；
                                            #   这里每轮确认"下一个连续数在不在"
                    y += 1                  # 在就继续向右延伸一格
                best = max(best, y - x + 1) # 这段长度 = 终点 y - 起点 x + 1，刷新最大值
                                            # 【API】max(a, b)：返回较大者
        return best


# ============================================================
# ② 输入解析层：stdin 原始文本 -> 逐组算法入参
#    唯一允许"读输入"的地方；交给算法的是干净的 Python 对象。
#    格式（见 题目.md）：每组两行 -- n / n 个整数，多组依次排列，读到 EOF 为止。
# ============================================================
def parse_input(text: str):
    """把 stdin 全文按组切开，逐组 yield 该组的数组 nums。

    【语法】yield 让函数变成生成器：main 里 for 一次拿一组，组数不定也能读到 EOF 自然结束。
    【语法】str.split() 不带参数 = 按任意空白切分并丢掉空串，所以一行或多行写法都能解析。
    """
    tokens = text.split()
    pos = 0                                     # 游标推进，别用 pop(0)（O(n)，多组会退化）
    while pos < len(tokens):
        n = int(tokens[pos]); pos += 1           # 【API】int(字符串)：输入全是字符串，必须自己转类型
        nums = [int(t) for t in tokens[pos:pos + n]]   # 【语法】列表推导式：把 n 个 token 逐个转 int
                                                        # 【语法】切片 tokens[a:b] 取左闭右开区间 [a,b)
        pos += n
        yield nums


# ============================================================
# ③ 输出格式化层：算法返回值 -> 该组用例的输出文本
#    只在这里做格式适配。本题答案是单个整数，直接转成字符串即可。
# ============================================================
def format_output(result) -> str:
    """一组用例输出一个整数（最长连续序列长度），多组时 main 用换行拼接。"""
    return str(result)                      # 【API】str(对象)：把 int 转成 "4" 这种纯数字字符串


# ============================================================
# ④ 驱动层：ACM 主流程（顶层直接调用，提交时不加 __main__ 包裹）
# ============================================================
def main():
    outs = []
    for nums in parse_input(sys.stdin.read()):  # 【API】sys.stdin.read()：一次读完整个标准输入
                                                #   返回 str；判题机把输入重定向进来，能读到全部内容
        outs.append(format_output(Solution().longestConsecutive(nums)))
    if outs:                                    # 空输入就别输出，否则会凭空多一个空行
        sys.stdout.write("\n".join(outs) + "\n")    # 【API】sys.stdout.write(s)：写字符串、不自动换行
                                                    #   所以手动补 "\n"；比多组循环 print 更快


main()
