#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# ============================================================
# LeetCode 11. 盛最多水的容器 (Container With Most Water)  |  难度：中等
# ------------------------------------------------------------
# 一句话：在柱状图里挑两根柱子，让它们与 x 轴围成的矩形面积（水量）最大，容器不能倾斜。
# 涉及知识点：双指针（对撞指针）· 贪心收缩 · min/max · O(1) 额外空间
#
# 提交方式：**整个文件就是 ACM/OJ 提交代码**——顶层直接跑 main()，从 stdin 读、往 stdout 写。
#
# 本地判题（in.txt 里串了 9 组用例）：
#     python lc_0011_盛最多水的容器.py < in.txt
#     diff <(python lc_0011_盛最多水的容器.py < in.txt) out.txt && echo PASS
#
# 脚本结构（四段解耦，改题时只动对应那一段）：
#   ① class Solution  -- 纯算法，与 LeetCode 提交区一致，不碰任何 IO
#   ② parse_input()   -- stdin 文本 -> 逐组实参（唯一负责"读"的地方）
#   ③ format_output() -- 算法返回值 -> 输出字符串（唯一负责"写"的地方）
#   ④ main()          -- ACM 主流程：逐组算、逐组输出
#
# 注释约定（算法层强制）：每个 API / 关键字 / 语法糖首次出现处都要解释，
# 三要素齐全 -- 作用 · 关键参数（含默认值）· 返回或副作用；同一 API 之后只写短注释。
# ============================================================

import sys
from typing import List


# ============================================================
# ① 核心算法：可整段复制回 LeetCode 提交区（方法签名与题面完全一致）
#    - 只依赖标准库
#    - 禁止出现 input() / print() / sys.stdin，保证 Solution 能脱离 IO 单独使用
# ============================================================
class Solution:
    def maxArea(self, height: List[int]) -> int:
        """双指针从两端向中间收拢，每次只移动较矮那一侧的指针。

        为什么对：容器水量 = min(左柱高, 右柱高) × 宽度，宽度 = right - left。
        若移动"较高"的一侧，min(左,右) 不可能变大（仍被较矮那根限制），
        宽度却变小，面积只可能更小，所以最优解不可能因"移高侧"而错过；
        只有移动较矮一侧，才有机会遇到更高的柱子、抬高水量的下限。
        两指针相遇之前，所有可能成为最优的 (left, right) 组合都被检查过，
        因此不会漏解——这是本题比暴力枚举 O(n^2) 快的核心。

        时间复杂度 O(n)：left、right 各往中间走一步，合计 n 步。
        空间复杂度 O(1)：只用 left / right / best 三个变量。

        关键 Python 语法（首次出现处详解，后续同款写法不再展开）：
          - min(a, b)：返回两参数中的较小值；max(a, b) 同理返回较大值。
          - len(可迭代对象)：返回元素个数，这里取数组长度来定右指针起点。
          - 多重赋值：`left, right = 0, n - 1` 一行同时给两个变量赋值。
        """
        left, right = 0, len(height) - 1    # 左右指针分别指向首、尾两根柱子
        best = 0                            # 历史最大水量，初始 0

        while left < right:                 # 指针没相遇就说明宽度 >= 1，还有容器可算
                                            # 【易错】写成 left <= right 会让两指针同根，宽为 0，
                                            #   且高度取同一根，结果恒为 0，等于白算
            area = min(height[left], height[right]) * (right - left)   # 【API】min(a, b) 取两数较小者
                                                                       #   容器高度由较矮柱子决定（水不能倾斜）
                                                                       #   【API】right - left：两柱下标差即底边宽度
            best = max(best, area)          # 【API】max(a, b) 取两数较大者，更新历史最优
                                            # 【易错】写成 best = area 会把之前的最优解覆盖丢
            if height[left] < height[right]:
                left += 1                   # 左边更矮 -> 向右挪左指针，才有机会换到更高的左柱
            else:
                right -= 1                  # 右边更矮或等高 -> 向左挪右指针（等高时移哪边都等价）

        return best                         # 空数组 / 单元素时 while 不执行，best 恒为 0，天然正确


# ============================================================
# ② 输入解析层：stdin 原始文本 -> 逐组算法入参
#    唯一允许"读输入"的地方；交给算法的是干净的 Python 对象。
#    格式（见 题目.md）：每组两行 —— n / n 个整数，多组依次排列，读到 EOF 为止。
# ============================================================
def parse_input(text: str):
    """把 stdin 全文按组切开，逐组 yield height（柱子高度数组）。

    【语法】yield 让函数变成生成器：main 里 for 一次拿一组，
            不用把全部用例先存进内存，也就天然支持"组数不定、读到 EOF 为止"。
    【语法】str.split() 不带参数 = 按任意空白切分并丢掉空串，
            所以每组是写成两行还是挤成一行都能正确切分。
    """
    tokens = text.split()
    pos = 0                                     # 游标：tokens 是列表，用下标推进最直观
                                                # 【易错】别用 tokens.pop(0) 删头：list.pop(0) 是 O(n)，
                                                #   多组数据会退化成 O(n^2)
    while pos < len(tokens):
        n = int(tokens[pos]); pos += 1          # 【API】int(字符串)：输入全是字符串，必须自己转类型
        height = [int(t) for t in tokens[pos:pos + n]]    # 【语法】切片左闭右开，正好取 n 个；
                                                #   n=0 时切片为空列表，对应"空数组"边界用例
        pos += n
        yield height


# ============================================================
# ③ 输出格式化层：算法返回值 -> 该组用例的输出文本
#    只在这里做格式适配（空格分隔？带方括号？定位小数？），算法不用改。
# ============================================================
def format_output(result) -> str:
    """每组输出一行一个整数（最大水量）。

    【API】str(对象)：转成字符串；int 直接返回十进制写法，如 49。
    """
    return str(result)


# ============================================================
# ④ 驱动层：ACM 主流程（顶层直接调用，提交时不加 __main__ 包裹）
# ============================================================
def main():
    outs = []
    for height in parse_input(sys.stdin.read()):    # 【API】sys.stdin.read()：一次读完整个标准输入
                                                    #   返回 str；判题机把输入重定向进来，能读到全部内容
        outs.append(format_output(Solution().maxArea(height)))
    if outs:                                    # 空输入就别输出，否则会凭空多一个空行
        sys.stdout.write("\n".join(outs) + "\n")    # 【API】sys.stdout.write(s)：写字符串、不自动换行，
                                                    #   所以手动补 "\n"；比多组循环 print 更快


main()
