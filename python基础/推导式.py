# ========== 1. 列表推导式 ==========

# ---------- 例 1：筛选长度 > 3 的名字，统一转大写 ----------
print("\n"+"="*60)                    # 输出分隔块（固定样式）：60 个 = 起头，先换行防止挤在上一行
print("【example 1】列表推导式：筛选长度 > 3 的名字并转大写")
print("="*60)
names = ["Alice", "Bob", "Charlie", "David", "Eve"]  # 原始名字列表
# 推导式骨架：[表达式 for 变量 in 可迭代对象 if 条件] —— 遍历 → if 过滤 → 套表达式，逐个收进新列表
# 【API】str.upper() —— 作用：把字符串全部转大写；参数：无；返回：新字符串，原字符串不动
# 【API】len(obj) —— 作用：数元素个数；参数：字符串/列表/元组/字典等；返回：个数（整数）
new_names = [name.upper() for name in names if len(name) > 3]
print(new_names)  # ['ALICE', 'CHARLIE', 'DAVID'] —— Bob 和 Eve 长度=3，被 if 筛掉
print("-"*60)                         # 输出收尾线（固定样式）

# 【本段知识点】
# 1. 推导式从右往左读：for 决定遍历谁，if 决定留谁，最左边那截决定每个元素最终长什么样。
# 2. upper() 能转大写说明字符串不可变：所有"改"字符串的操作都是产出新字符串，原值不动。
# 3. 这里的 if 在 for 后面是"过滤"；若把 if 挪到表达式那边（x if 条件 else y）就变成三目选择，两个别混。

# ---------- 例 2：取 0~29 中 5 的倍数 ----------
print("\n"+"="*60)
print("【example 2】列表推导式：取 0~29 中 5 的倍数")
print("="*60)
multiples = [i for i in range(30) if i % 5 == 0]  # % 是取余，i%5==0 说明能被 5 整除
# 【API】range(n) —— 作用：生成 0 到 n-1 的整数序列；参数：n（必填）；返回：range 对象，惰性、省内存
print(multiples)  # [0, 5, 10, 15, 20, 25] —— 没有 30，因为 range(30) 不含 30
print("-"*60)

# 【本段知识点】
# 1. range(30) 是左闭右开：产出 0~29，含 0 不含 30，所以 30 本身永远不会出现。
# 2. i % 5 == 0 判断"能整除"：余数为 0 即倍数，是推导式里最常用的筛法。
# 3. range 是惰性序列：不一次性把 30 个数存进内存，用的时候才吐，遍历大范围很省。

# ========== 2. 字典推导式 ==========

# ---------- 例 1：单词 -> 单词长度 的键值对 ----------
print("\n"+"="*60)
print("【example 3】字典推导式：单词 -> 长度")
print("="*60)
listdemo = ['Google','Runoob','Taobao']  # 三个词恰好都 6 个字母
# 字典推导式骨架：{键表达式 : 值表达式 for 变量 in 可迭代对象} —— 和列表推导式几乎一样，只是每项多出"键:值"两截
newdict = {key:len(key) for key in listdemo }  # 冒号左边是键，右边是值
print(newdict)  # {'Google': 6, 'Runoob': 6, 'Taobao': 6}
print("-"*60)

# 【本段知识点】
# 1. 判断推导式结果类型看括号和冒号：花括号里带"键:值"是字典，不带冒号是集合（下一节）。
# 2. 键必须唯一：单词本身当键互不重复，所以三个条目都留得住。
# 3. len() 这里数的是每个单词的字符数当值，和第一节的 len() 是同一个函数。

# ---------- 例 2：数字 -> 平方 的键值对 ----------
print("\n"+"="*60)
print("【example 4】字典推导式：数字 -> 平方")
print("="*60)
dic = {x:x**2 for x in (2,4,6)}  # ** 是幂运算，x**2 即 x 的平方
print(dic)  # {2: 4, 4: 16, 6: 36}
print("-"*60)

# 【本段知识点】
# 1. 推导式的数据源不限于列表：元组 (2,4,6) 一样能喂，任何可迭代对象都行。
# 2. ** 是幂运算：x**2 是 x 的平方，别和 ^（按位异或）搞混。
# 3. Python 3.7+ 字典保序，键按插入顺序排，所以打印出来是 2、4、6 的顺序。

# ========== 3. 集合推导式 ==========
print("\n"+"="*60)
print("【example 5】集合推导式：平方集合（去重、无序）")
print("="*60)
setnew = {i**2 for i in (1,2,3)}  # 外层花括号但无冒号 → 集合，自动去重、无序
print(setnew)  # {1, 4, 9}
print("-"*60)

# 【本段知识点】
# 1. 花括号 + 无冒号 = 集合推导式；花括号 + 冒号 = 字典推导式，只差一个冒号。
# 2. 集合自动去重且无序：就算 for 出重复值也只留一份，打印顺序不一定等于输入顺序。
# 3. 集合元素必须是不可变类型（数字、字符串、元组）；列表这种可变类型塞进去会直接报错。

# ========== 4. "元组推导式"（实际是生成器表达式） ==========
print("\n"+"="*60)
print("【example 6】生成器表达式：\"元组推导式\"的真身")
print("="*60)
a = (x for x in range(1,10))  # 圆括号包住的不是元组，而是生成器表达式（惰性）
print(a)  # <generator object <genexpr> at 0x...> —— 生成器还没真正计算
# 【API】tuple(obj) —— 作用：把可迭代对象逐项取出来组成元组；参数：可迭代对象（列表/生成器等）；返回：新元组
print(tuple(a))  # (1, 2, 3, 4, 5, 6, 7, 8, 9) —— tuple() 把生成器逐项"逼"成元组
print("-"*60)

# 【本段知识点】
# 1. 圆括号包住的推导式不叫"元组推导式"——元组推导式不存在，它是生成器表达式（Generator Expression）。
# 2. 生成器是惰性的：print(a) 只显示生成器对象，值一个都没算；直到 tuple(a) 才开始逐项取值。
# 3. 取舍口诀：要"一次性拿全量结果"用列表推导式；只要逐个消费、想省内存就用生成器表达式。
